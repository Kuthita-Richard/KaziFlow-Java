package com.kaziflow.network;

import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

/**
 * RemoteStatement — backs Connection.createStatement().executeQuery(sql) /
 * executeUpdate(sql) / execute(sql), the no-bound-params path used a few
 * places across the DAOs (e.g. DatabaseManager.createTables(), simple
 * COUNT(*) queries). Each call is its own one-shot round trip to the server.
 */
public class RemoteStatement implements Statement {

    private final RemoteConnection conn;

    public RemoteStatement(RemoteConnection conn) { this.conn = conn; }

    @Override
    public ResultSet executeQuery(String sql) throws SQLException {
        NetProtocol.Request req = new NetProtocol.Request();
        req.op = NetProtocol.OP_EXECUTE_QUERY;
        req.sql = sql;
        NetProtocol.Response resp = conn.send(req);
        return new RemoteResultSet(resp.columns, resp.rows);
    }

    @Override
    public int executeUpdate(String sql) throws SQLException {
        NetProtocol.Request req = new NetProtocol.Request();
        req.op = NetProtocol.OP_EXECUTE_UPDATE;
        req.sql = sql;
        NetProtocol.Response resp = conn.send(req);
        return resp.updateCount;
    }

    @Override
    public boolean execute(String sql) throws SQLException {
        NetProtocol.Request req = new NetProtocol.Request();
        req.op = NetProtocol.OP_EXECUTE;
        req.sql = sql;
        conn.send(req);
        return false; // this codebase never inspects the return value of Statement.execute()
    }

    @Override public void close() {}
    @Override public java.sql.Connection getConnection() { return conn; }

    private static UnsupportedOperationException unsupported(String method) {
        return new UnsupportedOperationException("RemoteStatement." + method + "() is not implemented — not used by this codebase's DAOs.");
    }

    @Override public int getMaxFieldSize() { throw unsupported("getMaxFieldSize"); }
    @Override public void setMaxFieldSize(int max) { }
    @Override public int getMaxRows() { throw unsupported("getMaxRows"); }
    @Override public void setMaxRows(int max) { }
    @Override public void setEscapeProcessing(boolean enable) { }
    @Override public int getQueryTimeout() { return 0; }
    @Override public void setQueryTimeout(int seconds) { }
    @Override public void cancel() { throw unsupported("cancel"); }
    @Override public java.sql.SQLWarning getWarnings() { return null; }
    @Override public void clearWarnings() { }
    @Override public void setCursorName(String name) { throw unsupported("setCursorName"); }
    @Override public ResultSet getResultSet() { throw unsupported("getResultSet"); }
    @Override public int getUpdateCount() { throw unsupported("getUpdateCount"); }
    @Override public boolean getMoreResults() { return false; }
    @Override public void setFetchDirection(int direction) { }
    @Override public int getFetchDirection() { return ResultSet.FETCH_FORWARD; }
    @Override public void setFetchSize(int rows) { }
    @Override public int getFetchSize() { return 0; }
    @Override public int getResultSetConcurrency() { return ResultSet.CONCUR_READ_ONLY; }
    @Override public int getResultSetType() { return ResultSet.TYPE_FORWARD_ONLY; }
    @Override public void addBatch(String sql) { throw unsupported("addBatch"); }
    @Override public void clearBatch() { throw unsupported("clearBatch"); }
    @Override public int[] executeBatch() { throw unsupported("executeBatch"); }
    @Override public boolean getMoreResults(int current) { return false; }
    @Override public ResultSet getGeneratedKeys() { throw unsupported("getGeneratedKeys"); }
    @Override public int executeUpdate(String sql, int autoGeneratedKeys) throws SQLException { return executeUpdate(sql); }
    @Override public int executeUpdate(String sql, int[] columnIndexes) throws SQLException { return executeUpdate(sql); }
    @Override public int executeUpdate(String sql, String[] columnNames) throws SQLException { return executeUpdate(sql); }
    @Override public boolean execute(String sql, int autoGeneratedKeys) throws SQLException { return execute(sql); }
    @Override public boolean execute(String sql, int[] columnIndexes) throws SQLException { return execute(sql); }
    @Override public boolean execute(String sql, String[] columnNames) throws SQLException { return execute(sql); }
    @Override public int getResultSetHoldability() { throw unsupported("getResultSetHoldability"); }
    @Override public boolean isClosed() { return false; }
    @Override public void setPoolable(boolean poolable) { }
    @Override public boolean isPoolable() { return false; }
    @Override public void closeOnCompletion() { }
    @Override public boolean isCloseOnCompletion() { return false; }
    @Override public <T> T unwrap(Class<T> iface) { throw unsupported("unwrap"); }
    @Override public boolean isWrapperFor(Class<?> iface) { return false; }
}
