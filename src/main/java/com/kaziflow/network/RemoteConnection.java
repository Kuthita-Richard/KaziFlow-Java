package com.kaziflow.network;

import java.io.*;
import java.net.Socket;
import java.nio.charset.StandardCharsets;
import java.sql.*;
import java.util.Map;
import java.util.Properties;
import java.util.concurrent.Executor;

/**
 * RemoteConnection — the client side of "LAN server mode" (Phase 10D).
 *
 * Implements just enough of java.sql.Connection that every existing DAO in
 * this codebase keeps working completely unmodified: prepareStatement(sql),
 * prepareStatement(sql, RETURN_GENERATED_KEYS), createStatement(),
 * setAutoCommit(), commit(), rollback(), close(). Every DAO calls
 * DatabaseManager.getInstance().getConnection() exactly as before — it has
 * no idea whether the Connection it got back is local SQLite or this remote
 * proxy talking to another PC over the LAN.
 *
 * One dedicated TCP socket per RemoteConnection instance, held open for the
 * connection's lifetime (matching the try-with-resources pattern every DAO
 * already uses: `try (Connection conn = ...getConnection()) { ... }`).
 */
public class RemoteConnection implements Connection {

    private final Socket socket;
    private final BufferedReader in;
    private final PrintWriter out;
    private boolean closed = false;

    public RemoteConnection(String host, int port) throws SQLException {
        try {
            this.socket = new Socket(host, port);
            this.socket.setSoTimeout(15000);
            this.in = new BufferedReader(new InputStreamReader(socket.getInputStream(), StandardCharsets.UTF_8));
            this.out = new PrintWriter(new OutputStreamWriter(socket.getOutputStream(), StandardCharsets.UTF_8), true);
        } catch (IOException e) {
            throw new SQLException("Could not connect to KaziFlow network server at " + host + ":" + port + " — " + e.getMessage(), e);
        }
    }

    /** Sends one request and waits for the matching response. Package-private — used by RemoteStatement/RemotePreparedStatement. */
    synchronized NetProtocol.Response send(NetProtocol.Request req) throws SQLException {
        if (closed) throw new SQLException("Connection is closed");
        try {
            out.println(req.toJson());
            out.flush();
            String line = in.readLine();
            if (line == null) throw new SQLException("Network server closed the connection unexpectedly");
            NetProtocol.Response resp = NetProtocol.Response.fromJson(line);
            if (!resp.ok) throw new SQLException("Remote SQL error: " + resp.error);
            return resp;
        } catch (IOException e) {
            throw new SQLException("Network error talking to KaziFlow server: " + e.getMessage(), e);
        }
    }

    @Override
    public PreparedStatement prepareStatement(String sql) { return new RemotePreparedStatement(this, sql, false); }

    @Override
    public PreparedStatement prepareStatement(String sql, int autoGeneratedKeys) {
        return new RemotePreparedStatement(this, sql, autoGeneratedKeys == Statement.RETURN_GENERATED_KEYS);
    }

    @Override
    public Statement createStatement() { return new RemoteStatement(this); }

    @Override
    public void setAutoCommit(boolean autoCommit) throws SQLException {
        NetProtocol.Request req = new NetProtocol.Request();
        req.op = NetProtocol.OP_SET_AUTOCOMMIT;
        req.autoCommit = autoCommit;
        send(req);
    }

    @Override
    public void commit() throws SQLException {
        NetProtocol.Request req = new NetProtocol.Request();
        req.op = NetProtocol.OP_COMMIT;
        send(req);
    }

    @Override
    public void rollback() throws SQLException {
        NetProtocol.Request req = new NetProtocol.Request();
        req.op = NetProtocol.OP_ROLLBACK;
        send(req);
    }

    @Override
    public void close() {
        if (closed) return;
        closed = true;
        try {
            NetProtocol.Request req = new NetProtocol.Request();
            req.op = NetProtocol.OP_CLOSE;
            out.println(req.toJson());
            out.flush();
        } catch (Exception ignored) {}
        try { socket.close(); } catch (IOException ignored) {}
    }

    @Override public boolean isClosed() { return closed; }
    @Override public boolean getAutoCommit() { return false; } // this codebase always sets it explicitly before relying on it

    /** Quick reachability check used by the Settings → Network "Test Connection" button. */
    public boolean ping() {
        try {
            NetProtocol.Request req = new NetProtocol.Request();
            req.op = NetProtocol.OP_PING;
            NetProtocol.Response resp = send(req);
            return resp.ok;
        } catch (Exception e) { return false; }
    }

    private static UnsupportedOperationException unsupported(String method) {
        return new UnsupportedOperationException("RemoteConnection." + method + "() is not implemented — not used by this codebase's DAOs.");
    }

    @Override public CallableStatement prepareCall(String sql) { throw unsupported("prepareCall"); }
    @Override public String nativeSQL(String sql) { throw unsupported("nativeSQL"); }
    @Override public DatabaseMetaData getMetaData() { throw unsupported("getMetaData"); }
    @Override public void setReadOnly(boolean readOnly) { }
    @Override public boolean isReadOnly() { return false; }
    @Override public void setCatalog(String catalog) { }
    @Override public String getCatalog() { return null; }
    @Override public void setTransactionIsolation(int level) { }
    @Override public int getTransactionIsolation() { return TRANSACTION_READ_COMMITTED; }
    @Override public SQLWarning getWarnings() { return null; }
    @Override public void clearWarnings() { }
    @Override public Statement createStatement(int resultSetType, int resultSetConcurrency) { return createStatement(); }
    @Override public PreparedStatement prepareStatement(String sql, int resultSetType, int resultSetConcurrency) { return prepareStatement(sql); }
    @Override public CallableStatement prepareCall(String sql, int resultSetType, int resultSetConcurrency) { throw unsupported("prepareCall"); }
    @Override public Map<String, Class<?>> getTypeMap() { throw unsupported("getTypeMap"); }
    @Override public void setTypeMap(Map<String, Class<?>> map) { throw unsupported("setTypeMap"); }
    @Override public void setHoldability(int holdability) { }
    @Override public int getHoldability() { return ResultSet.CLOSE_CURSORS_AT_COMMIT; }
    @Override public Savepoint setSavepoint() { throw unsupported("setSavepoint"); }
    @Override public Savepoint setSavepoint(String name) { throw unsupported("setSavepoint"); }
    @Override public void rollback(Savepoint savepoint) { throw unsupported("rollback"); }
    @Override public void releaseSavepoint(Savepoint savepoint) { throw unsupported("releaseSavepoint"); }
    @Override public Statement createStatement(int resultSetType, int resultSetConcurrency, int resultSetHoldability) { return createStatement(); }
    @Override public PreparedStatement prepareStatement(String sql, int resultSetType, int resultSetConcurrency, int resultSetHoldability) { return prepareStatement(sql); }
    @Override public CallableStatement prepareCall(String sql, int resultSetType, int resultSetConcurrency, int resultSetHoldability) { throw unsupported("prepareCall"); }
    @Override public PreparedStatement prepareStatement(String sql, int[] columnIndexes) { return prepareStatement(sql, Statement.RETURN_GENERATED_KEYS); }
    @Override public PreparedStatement prepareStatement(String sql, String[] columnNames) { return prepareStatement(sql, Statement.RETURN_GENERATED_KEYS); }
    @Override public Clob createClob() { throw unsupported("createClob"); }
    @Override public Blob createBlob() { throw unsupported("createBlob"); }
    @Override public NClob createNClob() { throw unsupported("createNClob"); }
    @Override public SQLXML createSQLXML() { throw unsupported("createSQLXML"); }
    @Override public boolean isValid(int timeout) { return !closed; }
    @Override public void setClientInfo(String name, String value) { }
    @Override public void setClientInfo(Properties properties) { }
    @Override public String getClientInfo(String name) { return null; }
    @Override public Properties getClientInfo() { return new Properties(); }
    @Override public Array createArrayOf(String typeName, Object[] elements) { throw unsupported("createArrayOf"); }
    @Override public Struct createStruct(String typeName, Object[] attributes) { throw unsupported("createStruct"); }
    @Override public void setSchema(String schema) { }
    @Override public String getSchema() { return null; }
    @Override public void abort(Executor executor) { }
    @Override public void setNetworkTimeout(Executor executor, int milliseconds) { }
    @Override public int getNetworkTimeout() { return 0; }
    @Override public <T> T unwrap(Class<T> iface) { throw unsupported("unwrap"); }
    @Override public boolean isWrapperFor(Class<?> iface) { return false; }
}
